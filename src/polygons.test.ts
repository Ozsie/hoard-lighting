import { describe, expect, it } from 'vitest';
import {
  MAX_LIGHT_POLYGON_CACHE_ENTRIES,
  computeLightPolygon,
  lightInViewport,
  lightPolygonFor,
} from './polygons';
import {
  LightEffect,
  LightOcclusion,
  type LightingEnv,
  type LightSource,
  type LightViewport,
} from './types';

const CELL = 32;

// A synthetic environment from a letter grid: '#' and 'X' are opaque
// (walls and pillars), 'F' an undiscovered/fogged cell, any other letter an
// open cell; `roomOf` is the letter itself, so 'A' and 'B' are distinct
// regions.
const envFromGrid = (
  grid: string[],
  extra: Partial<LightingEnv> = {},
): LightingEnv => ({
  gridWidth: grid.reduce((max, row) => Math.max(max, row.length), 0),
  gridHeight: grid.length,
  cellOcclusion: (x, y) => {
    const cell = grid[y]?.[x] ?? '';
    if (cell === '') return LightOcclusion.FOG;
    if (cell === '#' || cell === 'X') return LightOcclusion.OPAQUE;
    if (cell === 'F') return LightOcclusion.FOG;
    return LightOcclusion.OPEN;
  },
  isStepBlocked: () => false,
  roomOf: (x, y) => grid[y]?.[x] ?? '',
  ...extra,
});

const light = (overrides: Partial<LightSource> = {}): LightSource => ({
  position: { x: 1, y: 1 },
  radius: 8,
  ...overrides,
});

// Finds the polygon point generated by the ray closest to the given
// angle. Refinement inserts extra rays between the base ones, so a ray's
// index in the point list is not known — its endpoint is the point whose
// direction from the light center matches the angle.
const rayEndpoint = (
  points: { x: number; y: number }[],
  angle: number,
  center = { x: 1.5 * CELL, y: 1.5 * CELL },
) => {
  let best = points[0];
  let bestDiff = Number.POSITIVE_INFINITY;
  for (const point of points) {
    let diff = Math.abs(
      Math.atan2(point.y - center.y, point.x - center.x) - angle,
    );
    diff = Math.min(diff, 2 * Math.PI - diff);
    if (diff < bestDiff) {
      best = point;
      bestDiff = diff;
    }
  }
  return best;
};

// Ray endpoints carry trig-level float error, so exact equality is wrong.
const expectRay = (
  point: { x: number; y: number },
  expected: { x: number; y: number },
) => {
  expect(point.x).toBeCloseTo(expected.x, 8);
  expect(point.y).toBeCloseTo(expected.y, 8);
};

// Parity test of a point against the polygon (world pixels).
const insidePolygon = (
  polygon: { x: number; y: number }[],
  point: { x: number; y: number },
): boolean => {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i].x;
    const yi = polygon[i].y;
    const xj = polygon[j].x;
    const yj = polygon[j].y;
    if (
      yi > point.y !== yj > point.y &&
      point.x < ((xj - xi) * (point.y - yi)) / (yj - yi) + xi
    ) {
      inside = !inside;
    }
  }
  return inside;
};

// Whether the straight segment between two world-pixel points crosses a
// wall cell's interior (past a small face margin, so wall-face stops and
// corner grazes do not count).
const crossesWallInterior = (
  from: { x: number; y: number },
  to: { x: number; y: number },
  grid: string[],
): boolean => {
  const steps = Math.max(
    1,
    Math.ceil(Math.hypot(to.x - from.x, to.y - from.y) / 2),
  );
  for (let s = 1; s < steps; s++) {
    const x = from.x + ((to.x - from.x) * s) / steps;
    const y = from.y + ((to.y - from.y) * s) / steps;
    if (grid[Math.floor(y / CELL)]?.[Math.floor(x / CELL)] !== '#') {
      continue;
    }
    const fx = x % CELL;
    const fy = y % CELL;
    if (Math.min(fx, CELL - fx, fy, CELL - fy) > 2) {
      return true;
    }
  }
  return false;
};

describe('computeLightPolygon', () => {
  it('casts one endpoint per ray on unobstructed ground', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    // Refinement only inserts where a chord crosses a blocker's interior:
    // open ground (and fog-boundary stops) keeps exactly the base rays.
    expect(computeLightPolygon(light(), env, CELL, 'open')).toHaveLength(120);
  });

  it('bounds the polygon by the light radius on open ground', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    const points = computeLightPolygon(light({ radius: 2 }), env, CELL, 'open');
    const center = { x: 1.5 * CELL, y: 1.5 * CELL };
    points.forEach((point) => {
      expect(
        Math.hypot(point.x - center.x, point.y - center.y),
      ).toBeLessThanOrEqual(2 * CELL + 0.000001);
    });
  });

  it('stops at an opaque wall and lights it partway in', () => {
    const env = envFromGrid(['#####', '#...#', '#...#', '#####']);
    const points = computeLightPolygon(light(), env, CELL, 'walls');
    // Ray to the right: enters the wall cell at x = 4*CELL and penetrates
    // half of the wall cell.
    expectRay(rayEndpoint(points, 0), { x: 4.5 * CELL, y: 1.5 * CELL });
    // Ray downward: same rule along y.
    expectRay(rayEndpoint(points, Math.PI / 2), {
      x: 1.5 * CELL,
      y: 3.5 * CELL,
    });
  });

  it('stops at the shared edge of a fog cell', () => {
    const env = envFromGrid(['.....', '...F.', '.....']);
    const points = computeLightPolygon(light(), env, CELL, 'fog');
    expectRay(rayEndpoint(points, 0), { x: 3 * CELL, y: 1.5 * CELL });
  });

  it('stops at the shared edge when the environment blocks the step', () => {
    const env = envFromGrid(['.....', '.....', '.....'], {
      isStepBlocked: (from, to) => from.x === 2 && from.y === 1 && to.x === 3,
    });
    const points = computeLightPolygon(light(), env, CELL, 'door');
    expectRay(rayEndpoint(points, 0), { x: 3 * CELL, y: 1.5 * CELL });
  });

  it('reads cells outside the grid as fog', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    const points = computeLightPolygon(light(), env, CELL, 'edge');
    expectRay(rayEndpoint(points, Math.PI / 2), {
      x: 1.5 * CELL,
      y: 3 * CELL,
    });
  });

  it('illuminates a blocking actor partway unless the light is a ceiling fixture', () => {
    const grid = ['.....', '.....', '.....'];
    const gridEnv = envFromGrid(grid);
    const actorEnv: LightingEnv = {
      ...gridEnv,
      cellOcclusion: (x, y) =>
        x === 3 && y === 1 ? LightOcclusion.ACTOR : gridEnv.cellOcclusion(x, y),
    };
    const points = computeLightPolygon(light(), actorEnv, CELL, 'actor');
    expectRay(rayEndpoint(points, 0), { x: 3.5 * CELL, y: 1.5 * CELL });

    // A ceiling light shines over actors.
    const ceiling = computeLightPolygon(
      light({ alignment: 'ceiling' }),
      actorEnv,
      CELL,
      'actor-ceiling',
    );
    expect(rayEndpoint(ceiling, 0).x).toBeGreaterThan(3.5 * CELL);

    // The light's own cell never blocks: an actor standing on the light
    // does not black it out.
    const own: LightingEnv = {
      ...gridEnv,
      cellOcclusion: (x, y) =>
        x === 1 && y === 1 ? LightOcclusion.ACTOR : gridEnv.cellOcclusion(x, y),
    };
    const ownPoints = computeLightPolygon(
      light({ radius: 2 }),
      own,
      CELL,
      'own',
    );
    const center = { x: 1.5 * CELL, y: 1.5 * CELL };
    ownPoints.forEach((point) => {
      expect(
        Math.hypot(point.x - center.x, point.y - center.y),
      ).toBeLessThanOrEqual(2 * CELL + 0.000001);
    });
  });

  it('keeps a gas cloud inside its room region', () => {
    const env = envFromGrid(['AAAB', 'AAAB', 'AAAB']);
    const points = computeLightPolygon(
      light({ effect: LightEffect.GAS, radius: 10 }),
      env,
      CELL,
      'gas',
    );
    // Every ray stops at the region boundary between the adjacent A cell
    // and the first B cell (or earlier).
    points.forEach((point) => {
      expect(point.x).toBeLessThanOrEqual(3 * CELL + 0.000001);
    });
    expectRay(rayEndpoint(points, 0), { x: 3 * CELL, y: 1.5 * CELL });
  });

  it('selects rays inside the beam cone for sweep lights', () => {
    const env = envFromGrid(['.....', '.....', '.....', '.....', '.....']);
    const sweep = light({ effect: LightEffect.SWEEP, radius: 1, rate: 50 });
    // At t = 0 the beam points right (angle 0): the rightward endpoint is
    // the light's full radius, the opposite endpoint collapses onto the
    // center.
    const points = computeLightPolygon(sweep, env, CELL, 'sweep', 0);
    // Sweep polygons keep the bare fixed-order rays: index-parallel to
    // the beam assembly, never refined.
    expect(points).toHaveLength(120);
    const center = { x: 1.5 * CELL, y: 1.5 * CELL };
    expectRay(rayEndpoint(points, 0), {
      x: center.x + CELL,
      y: center.y,
    });
    // Sweep polygons stay the bare 120 fixed-order rays (their assembly
    // is index-parallel), so the ray at angle π is exactly index 60.
    expectRay(points[60], center);
  });
});

describe('lightPolygonFor', () => {
  it('reuses the polygon while the occlusion state is unchanged', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    const key = 'stable';
    const first = lightPolygonFor(light({ radius: 1 }), env, CELL, key, 0);
    const second = lightPolygonFor(light({ radius: 1 }), env, CELL, key, 0);
    expect(second).toBe(first);
  });

  it('recomputes when the occlusion key or environment changes', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    const otherEnv = envFromGrid(['.....', '.....', '.....']);
    const l = light({ radius: 1 });
    const stable = lightPolygonFor(l, env, CELL, 'key', 0);
    const newKey = lightPolygonFor(l, env, CELL, 'other-key', 0);
    const newEnv = lightPolygonFor(l, otherEnv, CELL, 'key', 0);
    expect(newKey).not.toBe(stable);
    expect(newEnv).not.toBe(stable);
  });

  it('serves each environment independently even under the same key', () => {
    // Two different environments with the same key must not share
    // polygons — the environment identity, not the key alone, scopes the
    // cache.
    const open = envFromGrid(['.....', '...F.', '.....']);
    const walled = envFromGrid(['#####', '#..F#', '#####']);
    const l = light({ radius: 8, id: 'same' });
    const openPoints = lightPolygonFor(l, open, CELL, 'same-key', 0);
    const walledPoints = lightPolygonFor(l, walled, CELL, 'same-key', 0);
    expectRay(rayEndpoint(walledPoints, 0), {
      x: 3 * CELL,
      y: 1.5 * CELL,
    });
    // The open environment still computes fog-stop polygons on its own
    // terms, not the walled one's.
    expectRay(rayEndpoint(openPoints, Math.PI / 2), {
      x: 1.5 * CELL,
      y: 3 * CELL,
    });
  });
});

describe('occlusion cache invalidation contract', () => {
  // The occlusion key is the caller's token for everything the environment
  // callbacks can read out of state. These tests pin down what happens when
  // that contract is kept and when it is broken.

  // A 12x5 open room with a wall cell at (3, 1) that can be removed, as a
  // door or a discovered wall would change it.
  const mutableEnv = (isWall: () => boolean): LightingEnv => ({
    gridWidth: 12,
    gridHeight: 5,
    cellOcclusion: (x, y) =>
      isWall() && x === 3 && y === 1
        ? LightOcclusion.OPAQUE
        : LightOcclusion.OPEN,
    isStepBlocked: () => false,
    roomOf: () => 'A',
  });

  it('reuses stale occlusion when the callbacks change but the token does not', () => {
    let wall = true;
    const env = mutableEnv(() => wall);
    const l = light({ radius: 8, position: { x: 1, y: 1 } });
    const walled = lightPolygonFor(l, env, CELL, 'rev1', 0);
    // The wall cell is lit partway in: the ray stops halfway through it.
    expectRay(rayEndpoint(walled, 0), { x: 3.5 * CELL, y: 1.5 * CELL });

    // The wall is gone from the environment, but the token is unchanged:
    // the cached occlusion map and polygon are reused — stale by contract.
    wall = false;
    const stale = lightPolygonFor(l, env, CELL, 'rev1', 0);
    expect(stale).toBe(walled);
    expectRay(rayEndpoint(stale, 0), { x: 3.5 * CELL, y: 1.5 * CELL });

    // A changed token invalidates: the polygon is recomputed and the ray
    // now reaches the full radius.
    const fresh = lightPolygonFor(l, env, CELL, 'rev2', 0);
    expect(fresh).not.toBe(walled);
    expectRay(rayEndpoint(fresh, 0), { x: 9.5 * CELL, y: 1.5 * CELL });
  });

  it('treats cellSize as part of the occlusion key contract', () => {
    const env = envFromGrid(Array.from({ length: 12 }, () => '............'));
    const l = light({ radius: 2, id: 'sized', position: { x: 1, y: 1 } });
    const at32 = lightPolygonFor(l, env, 32, 'key', 0);
    expectRay(rayEndpoint(at32, 0), { x: 3.5 * 32, y: 1.5 * 32 });
    // Same key, different cell size: reused (stale) — the key must carry
    // cellSize, as the README example does.
    expect(lightPolygonFor(l, env, 64, 'key', 0)).toBe(at32);
    // A key that includes the cell size recomputes at the new scale.
    const at64 = lightPolygonFor(l, env, 64, 'key-64', 0);
    expect(at64).not.toBe(at32);
    expectRay(rayEndpoint(at64, 0, { x: 1.5 * 64, y: 1.5 * 64 }), {
      x: 3.5 * 64,
      y: 1.5 * 64,
    });
  });

  it('bounds the polygon cache and evicts the oldest entry first', () => {
    const env = envFromGrid(Array.from({ length: 12 }, () => '............'));
    const key = 'bounded';
    const first = light({ id: 'first', radius: 2, position: { x: 1, y: 1 } });
    const firstPoints = lightPolygonFor(first, env, CELL, key, 0);
    const last = light({
      id: 'last',
      radius: 2,
      position: { x: 9, y: 8 },
    });
    for (let i = 0; i < MAX_LIGHT_POLYGON_CACHE_ENTRIES - 1; i++) {
      lightPolygonFor(
        light({
          id: `filler-${i}`,
          radius: 2,
          position: { x: 2 + (i % 8), y: 1 + Math.floor(i / 8) },
        }),
        env,
        CELL,
        key,
        0,
      );
    }
    const lastPoints = lightPolygonFor(last, env, CELL, key, 0);
    // The cache held MAX entries when 'last' was inserted, so 'first' —
    // the oldest — was evicted and is recomputed on its next request,
    // while the most recent entry is still served from cache.
    expect(lightPolygonFor(last, env, CELL, key, 0)).toBe(lastPoints);
    expect(lightPolygonFor(first, env, CELL, key, 0)).not.toBe(firstPoints);
  });
});

describe('chord refinement', () => {
  // A 12x12 room, border-walled, with a wall column at x = 5 — optionally
  // with a one-cell doorway gap.
  const walledGrid = (gapY: number | null): string[] =>
    Array.from({ length: 12 }, (_, y) =>
      Array.from({ length: 12 }, (_, x) =>
        x === 0 || x === 11 || y === 0 || y === 11 || (x === 5 && y !== gapY)
          ? '#'
          : '.',
      ).join(''),
    );

  const walledEnv = (grid: string[]): LightingEnv => {
    const blocked = (x: number, y: number) => grid[y]?.[x] === '#';
    return {
      ...envFromGrid(grid),
      isStepBlocked: (from, to) =>
        blocked(to.x, to.y) || blocked(from.x, from.y),
    };
  };

  // Samples the inside of the polygon over the room and counts the points
  // whose straight segment to the light pokes through a wall's interior —
  // the light-on-the-far-side-of-a-wall leak.
  const leakCount = (
    points: { x: number; y: number }[],
    center: { x: number; y: number },
    grid: string[],
  ): number => {
    let leaks = 0;
    for (let x = CELL; x < 11 * CELL; x += 4) {
      for (let y = CELL; y < 11 * CELL; y += 4) {
        if (!insidePolygon(points, { x, y })) {
          continue;
        }
        if (crossesWallInterior(center, { x, y }, grid)) {
          leaks += 1;
        }
      }
    }
    return leaks;
  };

  it('never lights through a sealed wall column', () => {
    const grid = walledGrid(null);
    const env = walledEnv(grid);
    const center = { x: 2.5 * CELL, y: 7.5 * CELL };
    const points = computeLightPolygon(
      light({ position: { x: 2, y: 7 }, radius: 6 }),
      env,
      CELL,
      'sealed',
    );
    expect(leakCount(points, center, grid)).toBe(0);
  });

  it('keeps the light of a doorway off the wall faces around the gap', () => {
    const grid = walledGrid(6);
    const env = walledEnv(grid);
    const center = { x: 3.5 * CELL, y: 6.5 * CELL };
    const points = computeLightPolygon(
      light({ position: { x: 3, y: 6 }, radius: 6 }),
      env,
      CELL,
      'doorway',
    );
    expect(leakCount(points, center, grid)).toBe(0);
  });

  it('still lights through the doorway opening', () => {
    const grid = walledGrid(6);
    const env = walledEnv(grid);
    const points = computeLightPolygon(
      light({ position: { x: 3, y: 6 }, radius: 6 }),
      env,
      CELL,
      'doorway-open',
    );
    // Beyond the gap, straight through it: lit.
    expect(insidePolygon(points, { x: 6.5 * CELL, y: 6.5 * CELL })).toBe(true);
    // Beyond the column but off the gap's line of sight: dark.
    expect(insidePolygon(points, { x: 6.5 * CELL, y: 2.5 * CELL })).toBe(false);
  });
});

describe('lightInViewport', () => {
  const base = light({ radius: 2, position: { x: 10, y: 10 } });
  const viewport: LightViewport = { x: 0, y: 0, width: 5, height: 5 };

  it('passes every light without a viewport', () => {
    expect(lightInViewport(base, undefined)).toBe(true);
  });

  it('culls lights whose glow cannot reach the viewport', () => {
    expect(lightInViewport(base, viewport)).toBe(false);
  });

  it('keeps lights within reach of the viewport edge', () => {
    const near = light({ radius: 2, position: { x: 7, y: 2 } });
    expect(lightInViewport(near, viewport)).toBe(true);
    const far = light({ radius: 1, position: { x: 9, y: 5 } });
    expect(lightInViewport(far, viewport)).toBe(false);
  });

  it('always keeps gas lights, which have no cheap bound', () => {
    const gas = light({
      effect: LightEffect.GAS,
      radius: 2,
      position: { x: 90, y: 90 },
    });
    expect(lightInViewport(gas, viewport)).toBe(true);
  });
});
