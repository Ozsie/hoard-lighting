import { describe, expect, it } from 'vitest';
import {
  computeLightPolygon,
  lightInViewport,
  lightPolygonFor,
} from './polygons';
import {
  LightEffect,
  LightOcclusion,
  type LightingEnv,
  type LightSource,
  type LightViewport,
} from './types';

const CELL = 32;

// A synthetic environment from a letter grid: '#' and 'X' are opaque
// (walls and pillars), 'F' an undiscovered/fogged cell, any other letter an
// open cell; `roomOf` is the letter itself, so 'A' and 'B' are distinct
// regions.
const envFromGrid = (
  grid: string[],
  extra: Partial<LightingEnv> = {},
): LightingEnv => ({
  gridWidth: grid.reduce((max, row) => Math.max(max, row.length), 0),
  gridHeight: grid.length,
  cellOcclusion: (x, y) => {
    const cell = grid[y]?.[x] ?? '';
    if (cell === '') return LightOcclusion.FOG;
    if (cell === '#' || cell === 'X') return LightOcclusion.OPAQUE;
    if (cell === 'F') return LightOcclusion.FOG;
    return LightOcclusion.OPEN;
  },
  isStepBlocked: () => false,
  roomOf: (x, y) => grid[y]?.[x] ?? '',
  ...extra,
});

const light = (overrides: Partial<LightSource> = {}): LightSource => ({
  position: { x: 1, y: 1 },
  radius: 8,
  ...overrides,
});

// Finds the polygon point generated by the ray closest to the given angle.
const rayEndpoint = (points: { x: number; y: number }[], angle: number) => {
  const rayCount = points.length;
  const index =
    ((Math.round((angle / (2 * Math.PI)) * rayCount) % rayCount) + rayCount) %
    rayCount;
  return points[index];
};

// Ray endpoints carry trig-level float error, so exact equality is wrong.
const expectRay = (
  point: { x: number; y: number },
  expected: { x: number; y: number },
) => {
  expect(point.x).toBeCloseTo(expected.x, 8);
  expect(point.y).toBeCloseTo(expected.y, 8);
};

describe('computeLightPolygon', () => {
  it('casts one endpoint per ray', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    expect(computeLightPolygon(light(), env, CELL, 'open')).toHaveLength(120);
  });

  it('bounds the polygon by the light radius on open ground', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    const points = computeLightPolygon(light({ radius: 2 }), env, CELL, 'open');
    const center = { x: 1.5 * CELL, y: 1.5 * CELL };
    points.forEach((point) => {
      expect(
        Math.hypot(point.x - center.x, point.y - center.y),
      ).toBeLessThanOrEqual(2 * CELL + 0.000001);
    });
  });

  it('stops at an opaque wall and lights it partway in', () => {
    const env = envFromGrid(['#####', '#...#', '#...#', '#####']);
    const points = computeLightPolygon(light(), env, CELL, 'walls');
    // Ray to the right: enters the wall cell at x = 4*CELL and penetrates
    // half of the wall cell.
    expectRay(rayEndpoint(points, 0), { x: 4.5 * CELL, y: 1.5 * CELL });
    // Ray downward: same rule along y.
    expectRay(rayEndpoint(points, Math.PI / 2), {
      x: 1.5 * CELL,
      y: 3.5 * CELL,
    });
  });

  it('stops at the shared edge of a fog cell', () => {
    const env = envFromGrid(['.....', '...F.', '.....']);
    const points = computeLightPolygon(light(), env, CELL, 'fog');
    expectRay(rayEndpoint(points, 0), { x: 3 * CELL, y: 1.5 * CELL });
  });

  it('stops at the shared edge when the environment blocks the step', () => {
    const env = envFromGrid(['.....', '.....', '.....'], {
      isStepBlocked: (from, to) => from.x === 2 && from.y === 1 && to.x === 3,
    });
    const points = computeLightPolygon(light(), env, CELL, 'door');
    expectRay(rayEndpoint(points, 0), { x: 3 * CELL, y: 1.5 * CELL });
  });

  it('reads cells outside the grid as fog', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    const points = computeLightPolygon(light(), env, CELL, 'edge');
    expectRay(rayEndpoint(points, Math.PI / 2), {
      x: 1.5 * CELL,
      y: 3 * CELL,
    });
  });

  it('illuminates a blocking actor partway unless the light is a ceiling fixture', () => {
    const grid = ['.....', '.....', '.....'];
    const gridEnv = envFromGrid(grid);
    const actorEnv: LightingEnv = {
      ...gridEnv,
      cellOcclusion: (x, y) =>
        x === 3 && y === 1 ? LightOcclusion.ACTOR : gridEnv.cellOcclusion(x, y),
    };
    const points = computeLightPolygon(light(), actorEnv, CELL, 'actor');
    expectRay(rayEndpoint(points, 0), { x: 3.5 * CELL, y: 1.5 * CELL });

    // A ceiling light shines over actors.
    const ceiling = computeLightPolygon(
      light({ alignment: 'ceiling' }),
      actorEnv,
      CELL,
      'actor-ceiling',
    );
    expect(rayEndpoint(ceiling, 0).x).toBeGreaterThan(3.5 * CELL);

    // The light's own cell never blocks: an actor standing on the light
    // does not black it out.
    const own: LightingEnv = {
      ...gridEnv,
      cellOcclusion: (x, y) =>
        x === 1 && y === 1 ? LightOcclusion.ACTOR : gridEnv.cellOcclusion(x, y),
    };
    const ownPoints = computeLightPolygon(
      light({ radius: 2 }),
      own,
      CELL,
      'own',
    );
    const center = { x: 1.5 * CELL, y: 1.5 * CELL };
    ownPoints.forEach((point) => {
      expect(
        Math.hypot(point.x - center.x, point.y - center.y),
      ).toBeLessThanOrEqual(2 * CELL + 0.000001);
    });
  });

  it('keeps a gas cloud inside its room region', () => {
    const env = envFromGrid(['AAAB', 'AAAB', 'AAAB']);
    const points = computeLightPolygon(
      light({ effect: LightEffect.GAS, radius: 10 }),
      env,
      CELL,
      'gas',
    );
    // Every ray stops at the region boundary between the adjacent A cell
    // and the first B cell (or earlier).
    points.forEach((point) => {
      expect(point.x).toBeLessThanOrEqual(3 * CELL + 0.000001);
    });
    expectRay(rayEndpoint(points, 0), { x: 3 * CELL, y: 1.5 * CELL });
  });

  it('selects rays inside the beam cone for sweep lights', () => {
    const env = envFromGrid(['.....', '.....', '.....', '.....', '.....']);
    const sweep = light({ effect: LightEffect.SWEEP, radius: 1, rate: 50 });
    // At t = 0 the beam points right (angle 0): the rightward endpoint is
    // the light's full radius, the opposite endpoint collapses onto the
    // center.
    const points = computeLightPolygon(sweep, env, CELL, 'sweep', 0);
    const center = { x: 1.5 * CELL, y: 1.5 * CELL };
    expectRay(rayEndpoint(points, 0), {
      x: center.x + CELL,
      y: center.y,
    });
    expectRay(rayEndpoint(points, Math.PI), center);
  });
});

describe('lightPolygonFor', () => {
  it('reuses the polygon while the occlusion state is unchanged', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    const key = 'stable';
    const first = lightPolygonFor(light({ radius: 1 }), env, CELL, key, 0);
    const second = lightPolygonFor(light({ radius: 1 }), env, CELL, key, 0);
    expect(second).toBe(first);
  });

  it('recomputes when the occlusion key or environment changes', () => {
    const env = envFromGrid(['.....', '.....', '.....']);
    const otherEnv = envFromGrid(['.....', '.....', '.....']);
    const l = light({ radius: 1 });
    const stable = lightPolygonFor(l, env, CELL, 'key', 0);
    const newKey = lightPolygonFor(l, env, CELL, 'other-key', 0);
    const newEnv = lightPolygonFor(l, otherEnv, CELL, 'key', 0);
    expect(newKey).not.toBe(stable);
    expect(newEnv).not.toBe(stable);
  });

  it('serves each environment independently even under the same key', () => {
    // Two different environments with the same key must not share
    // polygons — the environment identity, not the key alone, scopes the
    // cache.
    const open = envFromGrid(['.....', '...F.', '.....']);
    const walled = envFromGrid(['#####', '#..F#', '#####']);
    const l = light({ radius: 8, id: 'same' });
    const openPoints = lightPolygonFor(l, open, CELL, 'same-key', 0);
    const walledPoints = lightPolygonFor(l, walled, CELL, 'same-key', 0);
    expectRay(rayEndpoint(walledPoints, 0), {
      x: 3 * CELL,
      y: 1.5 * CELL,
    });
    // The open environment still computes fog-stop polygons on its own
    // terms, not the walled one's.
    expectRay(rayEndpoint(openPoints, Math.PI / 2), {
      x: 1.5 * CELL,
      y: 3 * CELL,
    });
  });
});

describe('lightInViewport', () => {
  const base = light({ radius: 2, position: { x: 10, y: 10 } });
  const viewport: LightViewport = { x: 0, y: 0, width: 5, height: 5 };

  it('passes every light without a viewport', () => {
    expect(lightInViewport(base, undefined)).toBe(true);
  });

  it('culls lights whose glow cannot reach the viewport', () => {
    expect(lightInViewport(base, viewport)).toBe(false);
  });

  it('keeps lights within reach of the viewport edge', () => {
    const near = light({ radius: 2, position: { x: 7, y: 2 } });
    expect(lightInViewport(near, viewport)).toBe(true);
    const far = light({ radius: 1, position: { x: 9, y: 5 } });
    expect(lightInViewport(far, viewport)).toBe(false);
  });

  it('always keeps gas lights, which have no cheap bound', () => {
    const gas = light({
      effect: LightEffect.GAS,
      radius: 2,
      position: { x: 90, y: 90 },
    });
    expect(lightInViewport(gas, viewport)).toBe(true);
  });
});
